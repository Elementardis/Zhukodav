import fs from 'node:fs';
const read = name => JSON.parse(fs.readFileSync(new URL(`../locales/${name}.json`, import.meta.url), 'utf8'));
const ru = read('ru'), en = read('en'), context = read('context');
const parameters = text => [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort();
if (JSON.stringify(Object.keys(ru).sort()) !== JSON.stringify(Object.keys(en).sort())) throw Error('Locale keys differ');
for (const key of Object.keys(ru)) {
    if (!en[key]?.trim() || !ru[key]?.trim()) throw Error(`Empty translation: ${key}`);
    if (JSON.stringify(parameters(ru[key])) !== JSON.stringify(parameters(en[key]))) throw Error(`Parameters differ: ${key}`);
}
fs.writeFileSync(new URL('../js/messages.js', import.meta.url),
    '// Generated by node scripts/build-locales.mjs. Edit locales/*.json instead.\nexport const messages = ' + JSON.stringify({ ru, en }, null, 2) + ';\n');
const quote = value => '"' + String(value ?? '').replaceAll('"', '""') + '"';
const rows = [['key', 'ru', 'en', 'source', 'parameters'], ...Object.keys(ru).map(key =>
    [key, ru[key], en[key], context[key]?.source, JSON.stringify(context[key]?.parameters || {})])];
fs.writeFileSync(new URL('../locales/catalog.csv', import.meta.url), '\uFEFF' + rows.map(row => row.map(quote).join(',')).join('\r\n') + '\r\n');
console.log(`Validated and built ${Object.keys(ru).length} RU/EN messages and translator CSV.`);
